import { cn } from '@/lib/utils/cn';

/**
 * Decorative spinner. aria-hidden by design — the surrounding control or
 * region owns the announcement (aria-busy / aria-live), so a screen reader
 * is not told "loading" twice.
 */
export function Spinner({ className }: { className?: string }) {
  return (
    <svg
      className={cn('animate-spin', className)}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
      focusable="false"
    >
      <circle cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="3" opacity="0.25" />
      <path
        d="M22 12a10 10 0 0 1-10 10"
        stroke="currentColor"
        strokeWidth="3"
        strokeLinecap="round"
      />
    </svg>
  );
}
